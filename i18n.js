function setLanguage(lang) {
  const dict = translations[lang] || translations.fa;
  const html = document.documentElement;

  html.lang = lang;
  html.dir = lang === "fa" ? "rtl" : "ltr";

  // Update page title & meta description
  if (dict["meta.title"]) document.title = dict["meta.title"];
  const metaDesc = document.querySelector('meta[name="description"]');
  if (metaDesc && dict["meta.desc"]) metaDesc.setAttribute("content", dict["meta.desc"]);

  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    if (dict[key] !== undefined) {
      // Preserve child icons (e.g. SVG in buttons)
      const icon = el.querySelector("svg");
      if (icon) {
        el.innerHTML = "";
        el.appendChild(icon);
        el.append(" " + dict[key]);
      } else {
        el.textContent = dict[key];
      }
    }
  });

  // Update active language button
  document.querySelectorAll(".lang-btn").forEach(btn => {
    btn.classList.toggle("active", btn.dataset.lang === lang);
  });

  // Persist preference
  try {
    localStorage.setItem("cc-lang", lang);
  } catch (e) {}
}

function initI18n() {
  let lang = "fa";
  try {
    const saved = localStorage.getItem("cc-lang");
    if (saved && translations[saved]) lang = saved;
  } catch (e) {}

  setLanguage(lang);

  document.querySelectorAll(".lang-btn").forEach(btn => {
    btn.addEventListener("click", () => setLanguage(btn.dataset.lang));
  });
}

document.addEventListener("DOMContentLoaded", initI18n);
